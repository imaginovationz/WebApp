    INNER JOIN <DB_NAME>.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
    CROSS JOIN
    (
        SELECT 1 AS SEV_NUM, '1 - Showstopper' AS SEV_NAME
        UNION ALL
        SELECT 2 AS SEV_NUM, '2 - Critical' AS SEV_NAME
        UNION ALL
        SELECT 3 AS SEV_NUM, '3 - Non-critical' AS SEV_NAME
        UNION ALL
        SELECT 4 AS SEV_NUM, '4 - Live with' AS SEV_NAME
