            AND BUG.BG_DETECTED_IN_RCYC=RELEASE_CYCLES.RCYC_ID
            AND BG_STATUS='New'
        GROUP BY RELEASES.REL_ID, RELEASE_CYCLES.RCYC_NAME, LEFT(BG_SEVERITY, 1)
    ) AS B ON B.REL_ID=RELEASES.REL_ID AND B.RCYC_NAME=RELEASE_CYCLES.RCYC_NAME
    WHERE RELEASES.REL_ID=<SelectedReleaseID>
) AS New ON New.REL_ID=R.REL_ID AND New.RCYC_NAME=R.RCYC_NAME AND New.SEVERITY=R.SEV_NUM
