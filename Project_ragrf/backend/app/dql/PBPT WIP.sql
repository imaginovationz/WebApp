    COALESCE(MANUAL, 0) AS MANUAL
FROM mlidt_deposits_f19_db.dbo.RELEASES
INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
LEFT JOIN
(
    SELECT
        R.REL_ID,
        R.REL_NAME,
        R.REL_USER_TEMPLATE_01,
        R.REL_END_DATE,
        R.RCYC_NAME,
        SUM(CASE WHEN AUTOMATION='Y' THEN 1 ELSE 0 END) AS AUTOMATED,
        SUM(CASE wHEN AUTOMATION<>'Y' THEN 1 ELSE 0 END) AS MANUAL
    FROM
    (
        SELECT
            RELEASES.REL_ID,
            RELEASES.REL_NAME,
            RELEASES.REL_USER_TEMPLATE_01,
