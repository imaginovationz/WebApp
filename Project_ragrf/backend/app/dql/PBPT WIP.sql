        RELEASES.REL_ID,
        BUG.BG_USER_TEMPLATE_10 AS DETECTED_IN_PHASE,
        COUNT(*) AS BUG_COUNT
    FROM mlidt_deposits_f19_db.dbo.BUG
    INNER JOIN mlidt_deposits_f19_db.dbo.RELEASES ON RELEASES.REL_ID=BUG.BG_DETECTED_IN_REL
    WHERE BUG.BG_DETECTED_IN_REL=1051
        AND BUG.BG_USER_TEMPLATE_10='SIT'
    GROUP BY RELEASES.REL_ID, BUG.BG_USER_TEMPLATE_10
) AS SIT ON SIT.REL_ID=R.REL_ID
