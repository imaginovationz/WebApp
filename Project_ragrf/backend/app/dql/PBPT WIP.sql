            RELEASE_CYCLES.RCYC_NAME,
            RUN.RN_TEST_ID,
            TEST.TS_EXEC_STATUS,
            LEFT(TEST.TS_USER_TEMPLATE_12, 1) AS AUTOMATION,
            CAST(RUN.RN_EXECUTION_DATE AS DATE) AS RN_EXECUTION_DATE,
            RUN.RN_EXECUTION_TIME,
            ROW_NUMBER() OVER(PARTITION BY RELEASES.REL_ID, RELEASE_CYCLES.RCYC_NAME,RUN.RN_TEST_ID ORDER BY RUN.RN_EXECUTION_DATE DESC, RUN.RN_EXECUTION_TIME DESC) AS ROW_NUM
        FROM mlidt_deposits_f19_db.dbo.RELEASES
        INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
        INNER JOIN mlidt_deposits_f19_db.dbo.RUN ON RN_ASSIGN_RCYC=RELEASE_CYCLES.RCYC_ID
        INNER JOIN mlidt_deposits_f19_db.dbo.TEST ON TEST.TS_TEST_ID=RUN.RN_TEST_ID
        WHERE RUN.RN_RUN_ID IS NOT NULL
            AND RUN.RN_TEST_ID IS NOT NULL
            AND TEST.TS_RESPONSIBLE IS NOT NULL
            AND TEST.TS_EXEC_STATUS IN ('Passed', 'Failed', 'Not Completed')
            AND RELEASES.REL_ID=1051
    ) AS R
    WHERE R.ROW_NUM=1
        AND R.RN_EXECUTION_DATE=GET_DATE()
    GROUP BY REL_ID,REL_NAME,REL_USER_TEMPLATE_01,REL_END_DATE,RCYC_NAME
) AS R ON R.REL_ID=RELEASES.REL_ID AND R.RCYC_NAME=RELEASE_CYCLES.RCYC_NAME
WHERE RELEASES.REL_ID=1051


