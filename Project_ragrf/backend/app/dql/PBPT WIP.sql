--CUMULATIVE VARIANCES BY SEVERITY AND STATUS           
SELECT
    R.SEV_NUM,
    R.SEV_NAME,
    R.REL_ID,
    R.REL_NAME,
    R.REL_USER_TEMPLATE_01,
    R.REL_END_DATE,
    R.RCYC_NAME,
    COALESCE(New.BUG_COUNT, 0) AS New,
    COALESCE(Opened.BUG_COUNT, 0) AS Opened,
    COALESCE(Fixed.BUG_COUNT, 0) AS Fixed,
    COALESCE(Awaiting.BUG_COUNT, 0) AS Awaiting,
    COALESCE(Monitor.BUG_COUNT, 0) AS Monitor,
    COALESCE(Reopen.BUG_COUNT, 0) AS Reopen,
    COALESCE(Deferred.BUG_COUNT, 0) AS Deferred,
    COALESCE(Rejected.BUG_COUNT, 0) AS Rejected,
    COALESCE(Closed.BUG_COUNT, 0) AS Closed
FROM
(    
    SELECT
        SEV.SEV_NUM,
        SEV.SEV_NAME,
        RELEASES.REL_ID,
        RELEASES.REL_NAME,
        RELEASES.REL_USER_TEMPLATE_01,
        CAST(RELEASES.REL_END_DATE AS DATE) AS REL_END_DATE,
        RELEASE_CYCLES.RCYC_NAME    
    FROM mlidt_deposits_f19_db.dbo.RELEASES
    INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
    CROSS JOIN
    (
        SELECT 1 AS SEV_NUM, '1 - Showstopper' AS SEV_NAME
        UNION ALL
        SELECT 2 AS SEV_NUM, '2 - Critical' AS SEV_NAME
        UNION ALL
        SELECT 3 AS SEV_NUM, '3 - Non-critical' AS SEV_NAME
        UNION ALL
        SELECT 4 AS SEV_NUM, '4 - Live with' AS SEV_NAME
    ) AS SEV    
    WHERE RELEASES.REL_ID=1051
) R
LEFT JOIN
(
    SELECT
        RELEASES.REL_ID,
        RELEASE_CYCLES.RCYC_NAME,
        B.SEVERITY,
        B.BUG_COUNT
    FROM mlidt_deposits_f19_db.dbo.RELEASES
    INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
    LEFT JOIN
    (
        SELECT
            RELEASES.REL_ID,
            RELEASE_CYCLES.RCYC_NAME,
            LEFT(BG_SEVERITY, 1) AS SEVERITY,
            COUNT(*) AS BUG_COUNT
        FROM mlidt_deposits_f19_db.dbo.BUG
        INNER JOIN mlidt_deposits_f19_db.dbo.RELEASES ON RELEASES.REL_ID=BUG.BG_DETECTED_IN_REL
        INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
        WHERE RELEASES.REL_ID=1051
            AND BG_STATUS='New'
        GROUP BY RELEASES.REL_ID, RELEASE_CYCLES.RCYC_NAME, LEFT(BG_SEVERITY, 1)
    ) AS B ON B.REL_ID=RELEASES.REL_ID AND B.RCYC_NAME=RELEASE_CYCLES.RCYC_NAME
    WHERE RELEASES.REL_ID=1051
) AS New ON New.REL_ID=R.REL_ID AND New.RCYC_NAME=R.RCYC_NAME AND New.SEVERITY=R.SEV_NUM
LEFT JOIN
(
    SELECT
        RELEASES.REL_ID,
        RELEASE_CYCLES.RCYC_NAME,
        B.SEVERITY,
        B.BUG_COUNT
    FROM mlidt_deposits_f19_db.dbo.RELEASES
    INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
    LEFT JOIN
    (
        SELECT
            RELEASES.REL_ID,
            RELEASE_CYCLES.RCYC_NAME,
            LEFT(BG_SEVERITY, 1) AS SEVERITY,
            COUNT(*) AS BUG_COUNT
        FROM mlidt_deposits_f19_db.dbo.BUG
        INNER JOIN mlidt_deposits_f19_db.dbo.RELEASES ON RELEASES.REL_ID=BUG.BG_DETECTED_IN_REL
        INNER JOIN mlidt_deposits_f19_db.dbo.RELEASE_CYCLES ON RELEASE_CYCLES.RCYC_PARENT_ID=RELEASES.REL_ID
        WHERE RELEASES.REL_ID=1051
            AND BG_STATUS='Opened'
        GROUP BY RELEASES.REL_ID, RELEASE_CYCLES.RCYC_NAME, LEFT(BG_SEVERITY, 1)
    ) AS B ON B.REL_ID=RELEASES.REL_ID AND B.RCYC_NAME=RELEASE_CYCLES.RCYC_NAME
